import { useCallback, useEffect, useMemo, useRef } from 'react';
import {
  estimateFlowCost, getFlow, getFlowInstances, getFlowLogs, getFlowRuns, resumeFlowRun,
  rerunFlowRun, runFlow, stopFlow,
} from '../../api';
import { errorDetail } from '../toast';
import { useStream } from '../stream';
import { reconstructRunMessages } from './runFormat';
import { NODE_LIFECYCLE_TYPES } from './graphHelpers';
import { agentMessage, applyTurnEvent, isDelegationEvent, settleTurn } from '../chat/turnEvents';
import { trailStats } from './stepStats';
import { nodeStatusesFor } from './nodeStatus';
import { STEP_EVENTS, liveReplies, useLiveTurns, withLiveTurns } from '../runs/liveTurns';

const LIVE_STATUSES = new Set(['pending', 'running', 'stopping']);

// Whether a run's own lines say it is still going: its last flow-level line
// is its start.
function logsGoing(logs) {
  for (let i = (logs?.length || 0) - 1; i >= 0; i -= 1) {
    const ty = logs[i].type;
    if (ty === 'flow_finish' || ty === 'flow_stopped') return false;
    if (ty === 'flow_start') return true;
  }
  return false;
}


// The node's open log line (its agent_start that still holds a live turn),
// patched with `fn`; the same array when there is none.
function patchOpenNode(logs, nodeId, fn) {
  for (let i = logs.length - 1; i >= 0; i -= 1) {
    const l = logs[i];
    if (l.type === 'agent_start' && l.turn && (!nodeId || l.node_id === nodeId)) {
      const next = fn(l);
      if (next === l) return logs;
      const copy = [...logs];
      copy[i] = next;
      return copy;
    }
  }
  return logs;
}

// A fresh, unique token per chat thread. Generated on mount and regenerated by
// "New chat" so each thread gets its own conversation id. It must be unique
// (not a 0-based counter): the conversation id derives from it deterministically
// and resetting to a counter on reload would collide with already-persisted
// conversations (reusing their record + showing their old logs).
export const newChatNonce = () => `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;

/**
 * Everything about executing the flow and watching it run, for the run page
 * (pages/FlowRun.jsx): the runs list and History records, the live
 * chat-stream translation into flow-log events, the derived node statuses
 * and log slices the canvas/Logs panel render, and the run/stop/resume/
 * estimate actions. The run page never edits the flow, so a run starts from
 * the saved document; editing is the editor page's (useFlowDocument).
 * `taskId` is the task picked for the next run, `loadTasks` refreshes the
 * list it is picked from.
 */
export function useFlowRuns(deps) {
  const {
    chatNonce, flow, flowId, liveUpdates, loadTasks, logs,
    nodes, resumedChat, running, runs, taskId,
    selectedNode, selectedRunGroup, selectedWorkspace, setCenterTab,
    setChatNonce, setEstimate, setEstimating, setFlow, setInstances, setLogs,
    setResumedChat, setResumingRun, setRightTab, setRunNodeId, setRunning, setRuns,
    setSelectedNodeId, setSelectedRunGroup, setStopping, setStreamLogs, streamLogs,
    t, toast,
  } = deps;

  // node_id -> display label, captured from each turn's flow_meta so node_start /
  // node_done lines can show the agent name even though only flow_meta carries
  // the full node list.
  const nodeLabelsRef = useRef({});
  // True between a chat turn's flow_meta and its done, so the SSE flow_runs
  // listener can stand down while the stream is driving the view.
  const chatStreamingRef = useRef(false);
  // The node a step event without its own node_id belongs to.
  const currentNodeRef = useRef(null);

  // The conversation id FlowChat uses for the active chat. It is also the
  // run_group the backend stamps on this chat's flow-log events, so we can
  // scope the live Logs view to just the current chat. A resumed record keeps
  // its own id so continued turns grow that same record.
  const activeConversationId = resumedChat
    ? resumedChat.conversationId
    : chatNonce
    ? `flow-chat-${flowId}-${chatNonce}`
    : `flow-chat-${flowId}`;

  // The slice of `logs` (which holds every conversation's events for this flow)
  // relevant to what's on screen right now. Everything live, canvas node
  // statuses, the "executing" flag, the Logs panel, derives from THIS, never the
  // global `logs` tail. Scoping to the active conversation is what makes "New
  // chat" reset the view: a fresh conversation id has no events here, instead of
  // inheriting the previous chat's trailing flow_start/agent_start lines.
  const scopedLogs = useMemo(() => {
    // A selected History record -> only its events.
    if (selectedRunGroup) return logs.filter((l) => l.run_group === selectedRunGroup);
    // Manual Run / Run-node -> the most recent live run_group's tail.
    if (running || flow?.running) {
      const liveGroup = logs[logs.length - 1]?.run_group;
      return liveGroup ? logs.filter((l) => l.run_group === liveGroup) : logs;
    }
    // Chat -> live events streamed straight from the run (no refetch). streamLogs
    // is reset per conversation, so a fresh chat starts empty just like before.
    return streamLogs;
  }, [logs, streamLogs, selectedRunGroup, running, flow?.running]);

  const handleNewChat = () => {
    setChatNonce(newChatNonce());
    setCenterTab('chat');
    setResumedChat(null); // leave any resumed record; show the new (empty) chat
    setSelectedRunGroup(null);
    // Now, not after the conversation id has changed, so nothing on the page
    // takes the old chat's trail for the new one's (FlowRun's address).
    setStreamLogs([]);
    setSelectedNodeId(null);
  };

  const loadLogs = useCallback(async (workspaceName) => {
    if (!workspaceName) return;
    try {
      const response = await getFlowLogs(flowId, workspaceName);
      setLogs(response.data || []);
    } catch (error) {
      console.error('Failed to load logs', error);
    }
  }, [flowId, setLogs]);

  const loadRuns = useCallback(async (workspaceName) => {
    try {
      const response = await getFlowRuns(flowId, workspaceName || undefined);
      setRuns(response.data || []);
    } catch (error) {
      console.error('Failed to load runs', error);
    }
    try {
      const { data } = await getFlowInstances(flowId);
      const byId = {};
      (data || []).forEach((record) => {
        if (record?.flow_run_id) byId[record.flow_run_id] = record;
      });
      setInstances(byId);
    } catch (error) {
      console.error('Failed to load run records', error);
    }
  }, [flowId, setInstances, setRuns]);

  // Refresh logs + runs once at the end of a chat turn so the History list and
  // the persisted record catch up. Live progress no longer comes from here (see
  // handleStreamEvent), this is just the closing reconcile.
  const handleChatActivity = useCallback(() => {
    // Turn ended (normally, or via Stop/error where no `done` arrives): clear the
    // streaming guard so the SSE listener resumes, then reconcile once.
    chatStreamingRef.current = false;
    const ws = flow?.workspace || selectedWorkspace;
    if (!ws) return;
    loadLogs(ws);
    loadRuns(ws);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [flow?.workspace, selectedWorkspace]);

  // Translate a raw chat-stream event into the flow-log event shape the editor's
  // derivations (isExecuting, activeNodeId, nodeStatuses, FlowLog) consume, and
  // append it to the live stream-log buffer. This is the heart of the
  // stream-driven live view: every status the user sees during a chat run comes
  // from here, not from polling the backend.
  const handleStreamEvent = useCallback((event) => {
    const evType = event?.type;
    if (!evType) return;
    const ts = new Date().toISOString();
    if (evType === 'flow_meta') {
      const labels = {};
      for (const n of event.nodes || []) labels[n.node_id] = n.agent_label || n.agent_id;
      nodeLabelsRef.current = labels;
      chatStreamingRef.current = true;
      setStreamLogs((prev) => [...prev, { type: 'flow_start', timestamp: ts, content: t('flowEditor.flowStarted'), state: event.state, title: event.user_message }]);
    } else if (evType === 'node_start') {
      const label = event.agent_label || nodeLabelsRef.current[event.node_id] || event.agent_id || 'Agent';
      currentNodeRef.current = event.node_id;
      setStreamLogs((prev) => [...prev, {
        type: 'agent_start', node_id: event.node_id, agent_id: event.agent_id,
        agent_name: label, tag: 'agent', content: `Running ${label}`, timestamp: ts,
        run_id: event.run_id || null,
        // What the node was given, as the saved log line carries it.
        ...(event.input ? { input: event.input } : {}),
        // The node's steps as they happen, shown folded under its line.
        turn: agentMessage({ run_id: event.run_id || null }),
      }]);
    } else if (evType === 'node_done') {
      const label = event.agent_label || nodeLabelsRef.current[event.node_id] || event.agent_id || 'Agent';
      setStreamLogs((prev) => {
        // The steps move from the start line to the line that ends the node.
        let turn = null;
        const logs = patchOpenNode(prev, event.node_id, (l) => {
          turn = l.turn;
          const { turn: _moved, ...rest } = l;
          return rest;
        });
        const settled = turn ? settleTurn(turn, { content: event.response }) : null;
        return [...logs, {
          type: event.ok ? 'agent_finish' : 'agent_error', node_id: event.node_id,
          agent_id: event.agent_id, agent_name: label, tag: 'agent',
          content: event.ok ? `Completed ${label}` : `${label} failed`,
          output: event.response || event.error || event.summary || '', timestamp: ts,
          ...(event.route ? { route: event.route } : {}),
          run_id: event.run_id || turn?.run_id || null,
          ...(settled ? { turn: settled, stats: trailStats(settled.timeline) } : {}),
          // The files the node changed, as the saved log line carries them.
          files: (settled?.files || []).map(({ op, path, url }) => ({ op, path, ...(url ? { url } : {}) })),
          // Post-node shared-state snapshot for the live Runtime State block.
          state: event.state,
        }];
      });
    } else if (STEP_EVENTS.has(evType) || isDelegationEvent(event)) {
      const nodeId = event.node_id || currentNodeRef.current;
      setStreamLogs((prev) => patchOpenNode(prev, nodeId, (l) => {
        const turn = applyTurnEvent(l.turn, event);
        return turn === l.turn ? l : { ...l, turn };
      }));
    } else if (evType === 'node_skip') {
      setStreamLogs((prev) => [...prev, {
        type: 'node_skip', node_id: event.node_id, reason: event.reason || '',
        agent_name: nodeLabelsRef.current[event.node_id] || 'Node',
        // Why, when the stream says: a branch not chosen reads differently from a failure.
        content: event.reason
          ? t(`flowEditor.skipReasons.${event.reason}`, { defaultValue: t('flowEditor.skipped') })
          : t('flowEditor.skipped'),
        timestamp: ts,
      }]);
    } else if (evType === 'flow_summary') {
      // The turn's closing summary (the flow chat's Summary view), as the
      // saved log line carries it.
      setStreamLogs((prev) => [...prev, {
        type: 'flow_summary', content: t('flowEditor.summaryWritten'), output: event.content || '', timestamp: ts,
      }]);
    } else if (evType === 'done') {
      chatStreamingRef.current = false;
      setStreamLogs((prev) => [...prev, {
        type: event.ok === false ? 'flow_stopped' : 'flow_finish',
        content: event.ok === false ? t('flowEditor.flowStopped') : t('flowEditor.flowFinished'), timestamp: ts,
      }]);
    }
  }, [setStreamLogs, t]);

  // A fresh conversation (new chat / resumed record / flow change) starts with an
  // empty live buffer so it doesn't inherit the previous chat's execution trail.
  useEffect(() => {
    setStreamLogs([]);
    nodeLabelsRef.current = {};
    currentNodeRef.current = null;
    chatStreamingRef.current = false;
  }, [activeConversationId]); // eslint-disable-line react-hooks/exhaustive-deps

  const { on } = useStream();
  useEffect(() => {
    const workspaceName = flow?.workspace || selectedWorkspace;
    if (!workspaceName) return;
    loadTasks(workspaceName);
    loadLogs(workspaceName);
    loadRuns(workspaceName);
    if (!liveUpdates) return undefined;
    return on('app', async (ev) => {
      if (ev.type !== 'flow_runs.changed' && ev.type !== 'tasks.changed') return;
      // While a chat run is streaming, the live view is driven entirely by the
      // stream (handleStreamEvent); the backend emits a flow_runs.changed per log
      // event, so refetching here would be exactly the redundant churn we set out
      // to remove. Skip it, FlowChat's turn-end onActivity reconciles the
      // History list once the run finishes. Manual flow runs (flow.running) and
      // task changes still refetch normally.
      if (chatStreamingRef.current) return;
      loadLogs(workspaceName);
      loadRuns(workspaceName);
      if (flow?.running) {
        try {
          const res = await getFlow(flowId);
          setFlow((prev) => ({ ...prev, running: res.data.running }));
        } catch { /* keep the last known running state */ }
      }
    });
  }, [flowId, flow?.workspace, flow?.running, selectedWorkspace, liveUpdates, on, loadLogs, loadRuns]); // eslint-disable-line react-hooks/exhaustive-deps

  const activeNodeId = useMemo(() => {
    // Derive the running node from the log stream rather than flow.running, so
    // this works for both runFlow() runs and chat-driven runs (which don't flip
    // the flow's running flag). Scoped to the current conversation/run so a fresh
    // chat clears the highlight. If the flow has ended, nothing is active.
    if (scopedLogs.length) {
      const lastFlowEvent = [...scopedLogs].reverse().find(
        (l) => l.type === 'flow_finish' || l.type === 'flow_stopped'
      );
      const lastStart = [...scopedLogs].reverse().find((l) => l.type === 'flow_start');
      const ended = lastFlowEvent && (!lastStart || scopedLogs.indexOf(lastFlowEvent) > scopedLogs.indexOf(lastStart));
      if (ended) return null;
    }
    const lastType = {};
    for (const log of scopedLogs) {
      if (log.node_id && NODE_LIFECYCLE_TYPES.has(log.type)) lastType[log.node_id] = log.type;
    }
    return Object.entries(lastType).find(([, ty]) => ty === 'agent_start')?.[0] ?? null;
  }, [scopedLogs]);

  // True while a run is in progress, covers runFlow() (flow.running) and
  // chat-driven runs (latest flow-level log event is flow_start, not yet
  // finished/stopped). Used to drive the Logs auto-scroll.
  const isExecuting = useMemo(
    () => Boolean(running || flow?.running || logsGoing(scopedLogs)),
    [running, flow?.running, scopedLogs],
  );

  // When a run starts (rising edge of isExecuting), open the Logs tab so the
  // user sees execution progress. Only fires on the transition, so it won't
  // fight the user if they switch back to Graph mid-run.
  const wasExecutingRef = useRef(false);
  useEffect(() => {
    if (isExecuting && !wasExecutingRef.current) {
      // A fresh run started, drop any historical selection so the live stream
      // shows. A picked record whose own lines say it is still going is no
      // fresh run: it stays picked.
      // (A run started in the background and opened by its address, from the
      // chat that started it, is such a record.)
      // Lines not loaded yet say nothing: the record stays picked.
      if (!selectedRunGroup || ((running || flow?.running) && scopedLogs.length && !logsGoing(scopedLogs))) {
        setSelectedRunGroup(null);
      }
      setRightTab('logs');
    }
    wasExecutingRef.current = isExecuting;
  }, [isExecuting]); // eslint-disable-line react-hooks/exhaustive-deps

  // A live History record for the active chat run, built from the stream buffer
  // so the run shows up the moment it starts, with a status derived from the
  // latest boundary event (running -> completed/stopped), instead of only after
  // it finishes. The persisted record (loaded at turn end) takes over once it
  // exists, since it carries richer events for resume/replay.
  const liveChatRun = useMemo(() => {
    if (!streamLogs.length) return null;
    let status = 'running';
    for (let i = streamLogs.length - 1; i >= 0; i -= 1) {
      const ty = streamLogs[i].type;
      if (ty === 'flow_finish') { status = 'completed'; break; }
      if (ty === 'flow_stopped') { status = 'stopped'; break; }
      if (ty === 'flow_start') { status = 'running'; break; }
    }
    // Title the record by the conversation's first message (truncated), matching
    // the persisted record once it loads. Fall back to a generic label until the
    // first flow_start carries the message.
    const firstMsg = (streamLogs.find((l) => l.type === 'flow_start' && l.title)?.title || '').trim().replace(/\n/g, ' ');
    const title = firstMsg
      ? firstMsg.slice(0, 60) + (firstMsg.length > 60 ? '…' : '')
      : t('flowEditor.flowChat');
    return {
      run_group: activeConversationId,
      kind: 'chat',
      title,
      started_at: streamLogs[0]?.timestamp,
      status,
      events: streamLogs,
    };
  }, [streamLogs, t, activeConversationId]);

  const displayRuns = useMemo(() => {
    if (!liveChatRun) return runs;
    // Once the persisted record exists (post-reconcile), prefer it.
    if (runs.some((r) => r.run_group === liveChatRun.run_group)) return runs;
    return [liveChatRun, ...runs];
  }, [runs, liveChatRun]);

  const selectedRun = useMemo(
    () => displayRuns.find((r) => r.run_group === selectedRunGroup) || null,
    [displayRuns, selectedRunGroup]
  );

  // The log stream the right column renders:
  //  - a selected History record -> that record's own events
  //  - otherwise -> the run-scoped slice (scopedLogs). For chat this is the live
  //    stream buffer, which PERSISTS after the run ends so the finished run's
  //    logs + node statuses stay on screen until "New chat" clears them. A fresh
  //    chat has an empty buffer, so agents still read as pending when idle.
  // A run going on in the background (one an agent, a schedule or the Run
  // button started) streams on its own channel (common/run_stream.py): the
  // selected History record while it runs, or the flow's live run when
  // nothing is selected. Its nodes at work are laid over the stored log and
  // drawn as replies being written.
  const liveRunGroup = useMemo(() => {
    if (selectedRun) {
      return selectedRun.kind !== 'chat' && LIVE_STATUSES.has(selectedRun.status) ? selectedRun.run_group : null;
    }
    if (running || flow?.running) return scopedLogs[scopedLogs.length - 1]?.run_group || null;
    return null;
  }, [selectedRun, running, flow?.running, scopedLogs]);
  const liveTurns = useLiveTurns(liveRunGroup ? [`run:${liveRunGroup}`] : [], 'flow');

  const baseLogs = useMemo(() => {
    const stored = selectedRun ? (selectedRun.events || []) : scopedLogs;
    return liveRunGroup ? withLiveTurns(stored, liveTurns) : stored;
  }, [selectedRun, scopedLogs, liveRunGroup, liveTurns]);

  // Reconstruct the conversation bubbles for a selected History record from its
  // flow-log events (see reconstructRunMessages).
  const runMessages = useMemo(() => {
    if (!selectedRun) return [];
    return reconstructRunMessages(selectedRun);
  }, [selectedRun]);

  // The nodes of the selected run at work, as replies being written, and a
  // node just finished until its stored message is in (no blink between).
  const liveRunMessages = useMemo(
    () => (selectedRun && liveRunGroup ? liveReplies(liveTurns, runMessages) : []),
    [selectedRun, liveRunGroup, liveTurns, runMessages],
  );

  const visibleLogs = useMemo(() => {
    if (!selectedNode) return baseLogs;
    return baseLogs.filter(
      (log) => log.node_id === selectedNode.id || log.agent_id === selectedNode.data.agent_id
    );
  }, [baseLogs, selectedNode]);

  // Each node's status in the run on screen (nodeStatus.js): only the
  // latest pass counts, and a stopped run leaves nothing running or pending.
  const nodeStatuses = useMemo(
    () => nodeStatusesFor(nodes, baseLogs, running || flow?.running),
    [baseLogs, nodes, running, flow?.running],
  );

  const handleRunFlow = async () => {
    // A run always works on a chosen task; the server would otherwise invent
    // a "Flow: …" task from the flow's description.
    if (!flow || !taskId) return;
    const workspaceName = flow.workspace || selectedWorkspace;
    if (!workspaceName) {
      toast.error(t('flowEditor.selectWorkspaceFirst'));
      return;
    }
    setRunning(true);
    try {
      const started = await runFlow(flowId, {
        workspace: workspaceName,
        description: flow.description || '',
        task_id: taskId || undefined,
      });
      // The run endpoint prices the flow on the way out, so what a run is about
      // to cost lands in front of whoever pressed Run, not only on Estimate.
      const cost = started?.data?.estimated_cost;
      if (cost && typeof cost.total_usd === 'number') {
        toast.success(t('flowEditor.runStarted'), t('flowEditor.estimatedCost', { usd: cost.total_usd.toFixed(4) }));
      }
      setFlow((prev) => ({ ...prev, running: true }));
      await loadLogs(workspaceName);
      setRightTab('logs');
    } catch (error) {
      toast.error(t('flowEditor.runFailed'), errorDetail(error));
    } finally {
      setRunning(false);
    }
  };

  const handleEstimate = async () => {
    setEstimating(true);
    try {
      const { data } = await estimateFlowCost(flowId);
      setEstimate(data);
    } catch (error) {
      toast.error(t('flowEditor.estimateFailed'), errorDetail(error));
    } finally {
      setEstimating(false);
    }
  };

  // An answer, when given, is the reply to the question the run parked on.
  const handleResumeRun = async (flowRunId, answer) => {
    setResumingRun(flowRunId);
    try {
      await resumeFlowRun(flowRunId, answer);
      toast.success(t('flowEditor.runResumed'));
      await loadRuns(flow?.workspace || selectedWorkspace);
    } catch (error) {
      toast.error(t('flowEditor.resumeFailed'), errorDetail(error));
    } finally {
      setResumingRun(null);
    }
  };

  const handleStopFlow = async () => {
    if (!flow) return;
    setStopping(true);
    try {
      await stopFlow(flowId);
      const updated = await getFlow(flowId);
      setFlow(updated.data);
    } catch (error) {
      toast.error(t('flowEditor.stopFailed'), errorDetail(error));
    } finally {
      setStopping(false);
    }
  };

  // A past task run again from one node, as a new task run (flow/rerun.py).
  // A chat record runs again as a turn of its own conversation instead
  // (FlowChat rerunRequest), so it never comes here.
  const handleRerunTaskRun = async (nodeId, mode) => {
    const record = runs.find((r) => r.run_group === selectedRunGroup);
    if (!flow || !record || record.kind === 'chat') return;
    setRunNodeId(`${nodeId}:${mode}`);
    try {
      await rerunFlowRun(flowId, record.run_group, { node_id: nodeId, mode });
      setFlow((prev) => ({ ...prev, running: true }));
      await loadLogs(flow.workspace || selectedWorkspace);
      setRightTab('logs');
    } catch (error) {
      toast.error(t('flowEditor.nodePanel.rerunFailed'), errorDetail(error));
    } finally {
      setRunNodeId(null);
    }
  };

  return {
    activeConversationId, activeNodeId, baseLogs, displayRuns, handleChatActivity,
    handleEstimate, handleNewChat, handleRerunTaskRun, handleResumeRun, handleRunFlow,
    handleStopFlow, handleStreamEvent, isExecuting, loadLogs, loadRuns,
    liveRunMessages, nodeStatuses, runMessages, scopedLogs, selectedRun, visibleLogs,
  };
}

export default useFlowRuns;
